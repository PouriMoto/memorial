/**
 * The site is Persian-first. English exists only for the scrollytelling
 * page (home / memorial landing), so the English column mainly holds strings
 * used there and in the shared header/footer/CTA.
 */
export type Lang = 'fa' | 'en';

export type Localized = { fa: string; en?: string };

/** Pick the requested language, falling back to Persian. */
export function loc(value: Localized | undefined, lang: Lang): string {
  if (!value) return '';
  return (lang === 'en' ? value.en : undefined) ?? value.fa;
}

/** True when an English version of the value exists. */
export function hasEn(value: Localized | undefined): boolean {
  return Boolean(value?.en);
}

